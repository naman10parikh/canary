/**
 * The OpenTelemetry instrumentation generator — the heart of THE acceptance test.
 *
 * `canary instrument` does NOT run a service; it WIRES OpenTelemetry into a target
 * service so that, once the service is booted with `node --import ./canary-otel.mjs`,
 * a thrown error becomes a span `exception` event + `error.type`, and request latency
 * becomes an `http.server.request.duration` histogram (PLAN §5 steps 2–3; EXPERTISE-MAP
 * §1.5: "an exception is a span EVENT named `exception` with `exception.type/.message/
 * .stacktrace`; `error.type` is the stable classification attribute").
 *
 * Design (OPINIONS B2 "instrument ONCE in OpenTelemetry, never double-instrument per
 * backend"): one vendor-neutral OTLP wire feeds everything. The DEFAULT exporter is a
 * LOCAL file exporter ($0, no creds — the merge-gate path per Q0/D15); `--otlp file://X`
 * writes spans as JSONL to X; an `http(s)://` endpoint emits real OTLP. The emitted
 * bootstrap is SELF-CONTAINED (it inlines the file exporter) so the instrumented service
 * needs only the `@opentelemetry/*` packages, not canary's dist.
 *
 * The emitted bootstrap also honors the two semconv currency gotchas the brain flags:
 *   - `deployment.environment.name` (NOT the renamed-away `deployment.environment`) — §9.2
 *   - it never reads/writes `gen_ai.usage.*` (that token-cost seam is agentmoney's) — JOB 0
 */

import { mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve, join } from "node:path";
import { CanaryError } from "../lib/cli-result.js";

/** Where a span stream is exported. */
export type OtlpTarget =
  | { kind: "file"; dir: string } // local JSONL file sink ($0, the merge gate)
  | { kind: "otlp"; endpoint: string }; // a real OTLP HTTP endpoint

/** Structured result of an instrument run (the `--json` contract). */
export interface InstrumentResult {
  /** The target service directory that was instrumented. */
  dir: string;
  /** Files canary wrote into the target. */
  wired: string[];
  /** How spans will be exported. */
  exporter: { kind: "file"; path: string } | { kind: "otlp"; endpoint: string };
  /** Whether the Sentry source-map path was additionally wired. */
  sentry: boolean;
  /** A human-runnable proof command (boot with this, throw, read the sink). */
  spanProof: string;
  /** The semconv attribute canary instruments under (currency note, §9.2). */
  environmentAttribute: "deployment.environment.name";
  /** The boundary canary will NOT cross (JOB 0 — agentmoney owns token cost). */
  boundary: string;
}

/** Parse an `--otlp` flag value into a typed target. Defaults to a local file sink. */
export function parseOtlpTarget(raw: string | undefined): OtlpTarget {
  if (!raw) return { kind: "file", dir: ".otel-out" };
  if (raw.startsWith("file://")) {
    const dir = raw.slice("file://".length) || ".otel-out";
    return { kind: "file", dir };
  }
  if (raw.startsWith("http://") || raw.startsWith("https://")) {
    return { kind: "otlp", endpoint: raw };
  }
  throw new CanaryError(
    "BAD_INPUT",
    `--otlp must be a file:// path or an http(s):// endpoint, got: ${raw}`,
    { otlp: raw },
  );
}

const BOOTSTRAP_FILENAME = "canary-otel.mjs";

/**
 * Generate the self-contained OTel bootstrap the service loads via `node --import`.
 * It is plain ESM text (NOT TypeScript) so it runs in the target service directly.
 * The file exporter is INLINED so the service needs no canary dependency.
 */
export function renderBootstrap(target: OtlpTarget, serviceName: string): string {
  const exporterBlock =
    target.kind === "file"
      ? renderFileExporterBlock(target.dir)
      : renderOtlpExporterBlock(target.endpoint);

  return `#!/usr/bin/env node
// GENERATED BY canary — do not edit by hand. Regenerate with: canary instrument <dir>
// Load it BEFORE your app: node --import ./${BOOTSTRAP_FILENAME} server.js
//
// What this wires (OPINIONS B2 — instrument once in OTel):
//   - HTTP auto-instrumentation -> http.server.request.duration histogram (latency)
//   - a thrown/unhandled error on a request -> span status ERROR + an "exception" event
//     carrying exception.type/.message/.stacktrace + the error.type attribute
//   - deployment.environment.name (NOT the renamed-away deployment.environment) — semconv §9.2
//   - canary NEVER touches gen_ai.usage.* (token cost is agentmoney's seam) — JOB 0
//
// ESM hook (load-bearing for ESM services): OTel auto-instrumentation patches core modules
// (node:http) via an import hook. For an ESM entrypoint (an .mjs / "type":"module" app), that
// hook MUST be register()'d BEFORE the app binds node:http — otherwise spans are silently never
// produced. This register() runs first; it is a no-op cost for CJS apps. Requires
// '@opentelemetry/instrumentation' to be resolvable in the service (a peer of the SDK packages).
import { register } from 'node:module';
register('@opentelemetry/instrumentation/hook.mjs', import.meta.url);

import { NodeSDK } from '@opentelemetry/sdk-node';
import { getNodeAutoInstrumentations } from '@opentelemetry/auto-instrumentations-node';
import { resourceFromAttributes } from '@opentelemetry/resources';
import {
  ATTR_SERVICE_NAME,
} from '@opentelemetry/semantic-conventions';

${exporterBlock}

const sdk = new NodeSDK({
  resource: resourceFromAttributes({
    [ATTR_SERVICE_NAME]: ${JSON.stringify(serviceName)},
    // Current semconv attribute (the un-renamed one). canary refuses to emit the
    // legacy 'deployment.environment' that an agent grepping old guidance expects.
    'deployment.environment.name': process.env.NODE_ENV || 'development',
  }),
  spanProcessors: [canarySpanProcessor],
  instrumentations: [
    getNodeAutoInstrumentations({
      // Keep the wire focused on HTTP health; do not auto-instrument fs (noise).
      '@opentelemetry/instrumentation-fs': { enabled: false },
    }),
  ],
});

sdk.start();

process.on('SIGTERM', () => { sdk.shutdown().finally(() => process.exit(0)); });
process.on('beforeExit', () => { sdk.shutdown(); });
`;
}

/**
 * The inlined LOCAL file exporter ($0 — the merge gate). It serializes each finished
 * span (name, status, attributes incl. error.type, and the `exception` event with its
 * exception.* fields) to one JSON line. E20's boot-and-throw.mjs reads this sink back.
 */
function renderFileExporterBlock(dir: string): string {
  const safeDir = JSON.stringify(dir);
  return `import { mkdirSync, appendFileSync } from 'node:fs';
import { join } from 'node:path';

// A zero-dependency local span sink. Writes finished spans as JSONL to ${dir}/spans.jsonl.
// This is the faithful local OTLP path (Q0/D15): no collector, no creds, no network.
mkdirSync(${safeDir}, { recursive: true });
const SPAN_SINK = join(${safeDir}, 'spans.jsonl');

const canarySpanProcessor = {
  onStart() {},
  async forceFlush() {},
  async shutdown() {},
  onEnd(span) {
    try {
      const record = {
        name: span.name,
        kind: span.kind,
        status: span.status,
        // error.type is the stable classification attribute (EXPERTISE-MAP §1.5).
        attributes: span.attributes,
        // an exception is recorded as a span EVENT named 'exception'.
        events: (span.events || []).map((e) => ({
          name: e.name,
          attributes: e.attributes,
          time: e.time,
        })),
        durationMs: span.duration ? span.duration[0] * 1e3 + span.duration[1] / 1e6 : 0,
        traceId: span.spanContext().traceId,
        spanId: span.spanContext().spanId,
      };
      appendFileSync(SPAN_SINK, JSON.stringify(record) + '\\n');
    } catch {
      // a span exporter must never crash the app it watches (§9.3) — swallow + continue.
    }
  },
};`;
}

/** The real-OTLP exporter block (additive; the file sink remains the merge gate). */
function renderOtlpExporterBlock(endpoint: string): string {
  const safeEndpoint = JSON.stringify(endpoint.replace(/\/$/, "") + "/v1/traces");
  return `import { BatchSpanProcessor } from '@opentelemetry/sdk-trace-base';
import { OTLPTraceExporter } from '@opentelemetry/exporter-trace-otlp-http';

// Emit real OTLP spans over HTTP to the configured endpoint. The local file sink is the
// merge-gate path; this is the additive "ship to a backend" path.
const canarySpanProcessor = new BatchSpanProcessor(
  new OTLPTraceExporter({ url: ${safeEndpoint} }),
);`;
}

/**
 * Wire OpenTelemetry into a target service directory: write the bootstrap (+ optional
 * Sentry source-map config) and return a structured result. Idempotent — re-running
 * overwrites the generated bootstrap (the §1.5 "instrument once" property).
 */
export async function instrumentService(opts: {
  dir: string;
  otlp?: string;
  sentry?: boolean;
}): Promise<InstrumentResult> {
  const dir = resolve(opts.dir);
  if (!existsSync(dir)) {
    throw new CanaryError("NOT_FOUND", `target directory does not exist: ${dir}`, {
      dir,
    });
  }

  const target = parseOtlpTarget(opts.otlp);
  const serviceName = await inferServiceName(dir);
  const bootstrap = renderBootstrap(target, serviceName);
  const bootstrapPath = join(dir, BOOTSTRAP_FILENAME);
  await writeFile(bootstrapPath, bootstrap, "utf8");

  const wired = [BOOTSTRAP_FILENAME];

  if (opts.sentry) {
    const sentryConfig = renderSentrySourceMapConfig(serviceName);
    const sentryPath = join(dir, "canary-sentry.config.mjs");
    await writeFile(sentryPath, sentryConfig, "utf8");
    wired.push("canary-sentry.config.mjs");
  }

  if (target.kind === "file") {
    await mkdir(resolve(dir, target.dir), { recursive: true }).catch(() => undefined);
  }

  const exporter =
    target.kind === "file"
      ? ({ kind: "file", path: join(dir, target.dir, "spans.jsonl") } as const)
      : ({ kind: "otlp", endpoint: target.endpoint } as const);

  return {
    dir,
    wired,
    exporter,
    sentry: Boolean(opts.sentry),
    spanProof: `node --import ./${BOOTSTRAP_FILENAME} <entrypoint>  # throw on a route → read ${target.kind === "file" ? join(target.dir, "spans.jsonl") : "your OTLP backend"}`,
    environmentAttribute: "deployment.environment.name",
    boundary:
      "canary reads gen_ai.client.operation.duration/.exception/error.type; it STOPS at gen_ai.usage.* (token cost is agentmoney's).",
  };
}

/** Best-effort service name from the target's package.json; falls back to the dir name. */
async function inferServiceName(dir: string): Promise<string> {
  const pkgPath = join(dir, "package.json");
  if (existsSync(pkgPath)) {
    try {
      const { readFile } = await import("node:fs/promises");
      const raw = await readFile(pkgPath, "utf8");
      const parsed = JSON.parse(raw) as { name?: unknown };
      if (typeof parsed.name === "string" && parsed.name.length > 0) return parsed.name;
    } catch {
      // fall through to dir name
    }
  }
  const parts = dir.split("/").filter(Boolean);
  return parts[parts.length - 1] ?? "service";
}

/**
 * The Sentry source-map path (OPINIONS B1: source maps are load-bearing infra, wired into
 * CI as inject→upload→deploy — NEVER post-incident). This emits a documented bundler-plugin
 * config stub the user wires into their build; canary does not run the upload itself.
 */
function renderSentrySourceMapConfig(serviceName: string): string {
  return `// GENERATED BY canary — Sentry source-map (Debug ID) wiring.
// OPINIONS B1: source maps are load-bearing infrastructure. Wire upload into CI in the
// order INJECT -> UPLOAD -> DEPLOY (KNOWN-PITFALLS §1.1). Symbolication only applies to
// errors that occur AFTER upload (§1.5) — never a post-incident scramble.
//
// 1. Add the bundler plugin to your build (pick your bundler):
//      import { sentryVitePlugin } from '@sentry/vite-plugin';      // or webpack/esbuild/rollup
// 2. Configure it so Debug IDs are injected and maps uploaded at build time:
export const canarySentry = {
  org: process.env.SENTRY_ORG,
  project: process.env.SENTRY_PROJECT,           // ${serviceName}
  authToken: process.env.SENTRY_AUTH_TOKEN,      // scopes: project:releases, org:read
  sourcemaps: { assets: './dist/**' },
  release: { create: true, setCommits: { auto: true } },
};
// NOTE: SDK must be >= 7.47.0 for debug_meta (§1.2). On SDK v9+, enableTracing/
// autoSessionTracking were REMOVED — use browserSessionIntegration()/tracesSampleRate (§3.1/§1b.3).
`;
}

