/**
 * MWMBR (Multi-Window Multi-Burn-Rate) SLO rule generator — the Sloth-style core.
 *
 * Per brain/BATTLE-TESTED-SCENARIOS.md S6 + OPINIONS' alerting stances:
 *   - The SLI is a RATIO (good/total), NEVER a raw quantile like "p99 > 300ms" — a raw
 *     quantile cannot be expressed as an error budget (the S6 footgun guard).
 *   - Three burn-rate tiers, each requiring BOTH a long AND a short window to breach
 *     (long = precision, short = fast reset): 14.4× fast/page, 6× medium/page, 1× slow/ticket.
 *   - Per-window error ratios are precomputed as RECORDING rules (inline rate(...[3d]) is
 *     expensive — KNOWN-PITFALLS §7.3).
 *   - "Don't hand-write this" (S6) — this generator IS the agent-committed Sloth equivalent:
 *     static YAML an agent commits, validated by `promtool check rules`.
 *
 * Output is plain Prometheus rules YAML (groups → rules), so `promtool check rules` passes.
 */

import { CanaryError } from "../lib/cli-result.js";

/** A single Prometheus rule (recording or alerting). */
interface PromRule {
  record?: string;
  alert?: string;
  expr: string;
  for?: string;
  labels?: Record<string, string>;
  annotations?: Record<string, string>;
}

/** The MWMBR burn-rate tiers (Google SRE Workbook Table 5-8). */
interface BurnTier {
  name: string;
  factor: number; // burn-rate multiplier
  longWindow: string; // precision window
  shortWindow: string; // fast-reset window
  severity: "page" | "ticket";
}

const MWMBR_TIERS: BurnTier[] = [
  { name: "Fast", factor: 14.4, longWindow: "1h", shortWindow: "5m", severity: "page" },
  { name: "Medium", factor: 6, longWindow: "6h", shortWindow: "30m", severity: "page" },
  { name: "Slow", factor: 1, longWindow: "3d", shortWindow: "6h", severity: "ticket" },
];

/** Every window referenced by the tiers (deduped) — each gets a recording rule. */
function ratioWindows(): string[] {
  const windows = new Set<string>();
  for (const t of MWMBR_TIERS) {
    windows.add(t.longWindow);
    windows.add(t.shortWindow);
  }
  return [...windows];
}

export interface SloGenInput {
  service: string;
  /** Availability target as a percentage, e.g. 99.9. */
  target: number;
}

export interface SloGenResult {
  service: string;
  target: number;
  /** error budget = 1 - SLO. */
  budget: number;
  /** the generated rules YAML. */
  yaml: string;
  /** the recording-rule metric names produced (per window). */
  recordingRules: string[];
  /** the alert names produced. */
  alertRules: string[];
  /** confirmation the SLI is a ratio, not a raw quantile. */
  sliKind: "ratio";
}

/** Validate the target and return the error budget (1 − SLO). */
function toBudget(target: number): number {
  if (!Number.isFinite(target) || target <= 0 || target >= 100) {
    throw new CanaryError(
      "BAD_INPUT",
      `--target must be a percentage in (0, 100), e.g. 99.9 — got: ${target}`,
      { target },
    );
  }
  // Round to kill IEEE-754 noise (1 - 99.9/100 = 0.0009999999999998899 → 0.001).
  return Number((1 - target / 100).toPrecision(10));
}

/** Sanitize a service name into a Prometheus-safe metric/job token. */
function safeJob(service: string): string {
  const token = service.trim().replace(/[^a-zA-Z0-9_]/g, "_");
  if (token.length === 0) {
    throw new CanaryError("BAD_INPUT", "--service must be a non-empty name", { service });
  }
  return token;
}

/**
 * Render YAML by hand (no yaml dep — a generator that can't crash). The shape is the
 * canonical Prometheus rules file; promtool parses it directly.
 */
function renderYaml(
  job: string,
  recording: PromRule[],
  alerts: PromRule[],
): string {
  const lines: string[] = [];
  lines.push("# GENERATED BY canary — MWMBR SLO rules (S6). Validate: promtool check rules <file>");
  lines.push("# SLI is a RATIO (good/total), never a raw quantile (the S6 footgun guard).");
  lines.push("groups:");
  lines.push(`  - name: ${job}_slo_recording`);
  lines.push("    rules:");
  for (const r of recording) {
    lines.push(`      - record: ${r.record}`);
    lines.push(`        expr: ${r.expr}`);
    if (r.labels) {
      lines.push("        labels:");
      for (const [k, v] of Object.entries(r.labels)) lines.push(`          ${k}: ${yamlScalar(v)}`);
    }
  }
  lines.push(`  - name: ${job}_slo_alerts`);
  lines.push("    rules:");
  for (const a of alerts) {
    lines.push(`      - alert: ${a.alert}`);
    lines.push(`        expr: ${blockScalar(a.expr)}`);
    if (a.for) lines.push(`        for: ${a.for}`);
    if (a.labels) {
      lines.push("        labels:");
      for (const [k, v] of Object.entries(a.labels)) lines.push(`          ${k}: ${yamlScalar(v)}`);
    }
    if (a.annotations) {
      lines.push("        annotations:");
      for (const [k, v] of Object.entries(a.annotations))
        lines.push(`          ${k}: ${quote(v)}`);
    }
  }
  return lines.join("\n") + "\n";
}

function quote(v: string): string {
  // Quote scalars that could be misparsed (annotations have spaces/parens/colons).
  return JSON.stringify(v);
}

/**
 * Emit a YAML scalar unquoted when it's a safe plain token (so label values render as
 * `severity: ticket`, not `severity: "ticket"` — the S6 verify greps the unquoted form),
 * and quoted otherwise. Prometheus accepts both; the unquoted form is the conventional one.
 */
function yamlScalar(v: string): string {
  return /^[A-Za-z_][A-Za-z0-9_-]*$/.test(v) ? v : JSON.stringify(v);
}

/** Render a multi-line expr as a YAML block scalar for readability + correctness. */
function blockScalar(expr: string): string {
  const lines = expr.split("\n");
  if (lines.length === 1) return expr;
  return ["|"].concat(lines.map((l) => `          ${l}`)).join("\n");
}

/** Generate the full MWMBR ruleset for a service + availability target. */
export function generateSloRules(input: SloGenInput): SloGenResult {
  const budget = toBudget(input.target);
  const job = safeJob(input.service);

  // Recording rules: per-window error RATIO (good/total expressed as errors/total).
  // SLI-as-ratio: job:slo_errors:ratio_rate<W> = sum(rate(errors[W])) / sum(rate(total[W])).
  const recording: PromRule[] = ratioWindows().map((w) => ({
    record: `job:slo_errors:ratio_rate${w}`,
    expr: `sum(rate(http_server_request_duration_seconds_count{job="${job}",error_type!=""}[${w}])) / sum(rate(http_server_request_duration_seconds_count{job="${job}"}[${w}]))`,
    labels: { job },
  }));

  // Alert rules: each tier compares both windows to (factor × budget) — long AND short.
  const alerts: PromRule[] = MWMBR_TIERS.map((tier) => {
    const threshold = (tier.factor * budget).toPrecision(6);
    const expr = [
      `job:slo_errors:ratio_rate${tier.longWindow}{job="${job}"} > (${tier.factor} * ${budget})`,
      "and",
      `job:slo_errors:ratio_rate${tier.shortWindow}{job="${job}"} > (${tier.factor} * ${budget})`,
    ].join("\n");
    return {
      alert: `ErrorBudgetBurn_${tier.name}`,
      expr,
      labels: { severity: tier.severity, job },
      annotations: {
        summary: `${input.service} burning error budget at ${tier.factor}x (${tier.severity})`,
        description: `${tier.longWindow} AND ${tier.shortWindow} error-ratio both exceed ${threshold} (${tier.factor}x of the ${input.target}% SLO budget ${budget}).`,
        burn_rate: String(tier.factor),
      },
    };
  });

  return {
    service: input.service,
    target: input.target,
    budget,
    yaml: renderYaml(job, recording, alerts),
    recordingRules: recording.map((r) => r.record ?? ""),
    alertRules: alerts.map((a) => a.alert ?? ""),
    sliKind: "ratio",
  };
}
